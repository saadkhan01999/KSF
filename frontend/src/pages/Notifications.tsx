/* Notifications: what KSF noticed while nobody was looking.

   These are generated by the system, not written by staff — low stock, near
   expiry, deliveries received. They regenerate on sign-in and after any stock
   movement, so the list is always current rather than a growing pile. */

import { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import {
  Bell, BellOff, CheckCheck, PackageX, CalendarClock, Truck, UserPlus,
  Info, AlertTriangle, RefreshCw, CircleAlert, LifeBuoy
} from 'lucide-react';
import { useApp } from '../context/AppContext';
import { useApiData, useAction } from '../hooks/useApi';
import { api } from '../services/api';
import {
  Button, StatCard, EmptyState, TableSkeleton, Tabs, Allow, Badge
} from '../components/ui';
import { ago, number, internalPath } from '../utils/format';
import type { AppNotification } from '../types';

interface NotificationResponse {
  data: AppNotification[];
  counts: { total: number; unread: number; critical: number; warnings: number };
}

const ICONS: Record<string, React.ReactNode> = {
  'low-stock': <PackageX size={18} />,
  'out-of-stock': <PackageX size={18} />,
  expiry: <CalendarClock size={18} />,
  purchase: <Truck size={18} />,
  staff: <UserPlus size={18} />,
  system: <Info size={18} />,
  support: <LifeBuoy size={18} />
};

const TONES: Record<string, { bg: string; fg: string }> = {
  danger: { bg: 'var(--danger-100)', fg: 'var(--danger-600)' },
  warn: { bg: 'var(--warn-100)', fg: 'var(--warn-600)' },
  success: { bg: 'var(--ok-100)', fg: 'var(--ok-600)' },
  info: { bg: 'var(--info-100)', fg: 'var(--info-600)' }
};

export default function Notifications() {
  const { ok, refreshWorkspace, isPlatform } = useApp();
  const { busy, run } = useAction();
  const navigate = useNavigate();
  /* The Super Admin's notices belong to the platform, not to a pharmacy. */
  const base = isPlatform ? '/platform/notifications' : '/notifications';

  const [filter, setFilter] = useState('all');
  const { data, loading, reload } = useApiData<NotificationResponse>(isPlatform ? base : `${base}?filter=${filter}`, [filter, base]);

  const counts = data?.counts;
  const items = (data?.data ?? []).filter((item) => !isPlatform || filter === 'all' || (filter === 'unread' ? !item.is_read : item.type === filter));

  const open = (item: AppNotification) => {
    if (!item.is_read) {
      void api.post(`${base}/${item.id}/read`).then(() => { void reload(true); void refreshWorkspace(); });
    }
    if (item.link) navigate(internalPath(item.link, base));
  };

  const markAll = () => run(
    () => api.post<{ marked: number }>(`${base}/read-all`),
    (result) => {
      ok('All caught up', `${result.marked} notification(s) marked as read.`);
      void reload(true);
      void refreshWorkspace();
    }
  );

  const rescan = () => run(
    () => api.post('/notifications/refresh'),
    () => { ok('Stock re-checked', 'Low stock and expiry alerts have been rebuilt.'); void reload(true); void refreshWorkspace(); }
  );

  return (
    <>
      <div className="page-head">
        <div>
          <h1>Notifications</h1>
          <p className="sub">
            {isPlatform
              ? 'What happened across the platform — support requests, sign-ups and payments that need you.'
              : 'Things KSF thinks you should know about — mostly stock running low and batches nearing expiry.'}
          </p>
        </div>
        <div className="actions">
          <Allow permission="inventory.read">
            <Button variant="outline" icon={<RefreshCw size={17} />} onClick={rescan} loading={busy}>
              Re-check stock
            </Button>
          </Allow>
          {(counts?.unread ?? 0) > 0 && (
            <Button variant="primary" icon={<CheckCheck size={18} />} onClick={markAll}>
              Mark all as read
            </Button>
          )}
        </div>
      </div>

      {!isPlatform && <div className="grid grid-4 mb-5">
        <StatCard label="Unread" value={number(counts?.unread ?? 0)} icon={<Bell size={20} />} tone={counts?.unread ? 'warn' : 'brand'} />
        <StatCard label="Urgent" value={number(counts?.critical ?? 0)} icon={<CircleAlert size={20} />} tone="danger" hint="out of stock or expired" />
        <StatCard label="Warnings" value={number(counts?.warnings ?? 0)} icon={<AlertTriangle size={20} />} tone="warn" hint="low stock, near expiry" />
        <StatCard label="Total on record" value={number(counts?.total ?? 0)} icon={<Info size={20} />} tone="info" />
      </div>}

      <Tabs
        value={filter}
        onChange={setFilter}
        tabs={isPlatform
          ? [
            { value: 'all', label: 'Everything', count: counts?.total },
            { value: 'unread', label: 'Unread', count: counts?.unread },
            { value: 'support', label: 'Support requests' },
            { value: 'billing', label: 'Billing' }
          ]
          : [
            { value: 'all', label: 'Everything', count: counts?.total },
            { value: 'unread', label: 'Unread', count: counts?.unread },
            { value: 'out-of-stock', label: 'Out of stock' },
            { value: 'low-stock', label: 'Low stock' },
            { value: 'expiry', label: 'Expiry' },
            { value: 'purchase', label: 'Deliveries' }
          ]}
      />

      <div className="table-wrap">
        {loading
          ? <TableSkeleton rows={7} columns={2} />
          : items.length === 0
            ? (
              <EmptyState
                icon={<BellOff size={30} />}
                title={filter === 'unread' ? 'Nothing unread' : 'Nothing to report'}
                message={filter === 'unread'
                  ? 'You are completely up to date.'
                  : 'KSF has not flagged anything. Stock levels and expiry dates all look healthy.'}
              />
            )
            : (
              <div>
                {items.map((item) => {
                  const tone = TONES[item.severity] ?? TONES.info;
                  return (
                    <div
                      className={`notif ${item.is_read ? '' : 'is-unread'}`}
                      key={item.id}
                      onClick={() => open(item)}
                      role="button"
                      tabIndex={0}
                      onKeyDown={(e) => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); open(item); } }}
                    >
                      <span className="ico" style={{ background: tone.bg, color: tone.fg }}>
                        {ICONS[item.type] ?? <Info size={18} />}
                      </span>
                      <div className="body">
                        <strong>{item.title}</strong>
                        {item.body && <p>{item.body}</p>}
                        <div className="row-tight mt-2">
                          <Badge tone={item.severity === 'success' ? 'ok' : (item.severity as 'warn' | 'danger' | 'info')} dot={false}>
                            {item.type.replace(/-/g, ' ')}
                          </Badge>
                          {item.link && <span className="t-xs t-brand t-semi">Tap to open →</span>}
                        </div>
                      </div>
                      <div className="col" style={{ alignItems: 'flex-end', gap: 6 }}>
                        <span className="when">{ago(item.created_at)}</span>
                        {!item.is_read && <span className="unread-dot" aria-label="Unread" />}
                      </div>
                    </div>
                  );
                })}
              </div>
            )}
      </div>

      {!isPlatform && <p className="t-xs t-dim t-center mt-5">
        Stock and expiry alerts are rebuilt automatically whenever stock moves, so this list reflects
        the shelf as it is right now — not a backlog.
      </p>}
    </>
  );
}
